export function getRoleLabel(role: MediaSourceRole): string {
  switch (role) {
    case 'playback':
      return 'Playback';
    case 'cantado':
      return 'Cantado';
    case 'instrumental':
      return 'Instrumental';
    case 'audio':
      return 'Áudio';
    case 'video-playback':
      return 'Vídeo Playback';
    case 'video-cantado':
      return 'Vídeo Cantado';
    case 'video':
      return 'Outro Vídeo';
  }
}

export function getRoleDefaultMediaType(role: MediaSourceRole): MediaSourceKind {
  if (role === 'video-playback' || role === 'video-cantado' || role === 'video') {
    return 'video';
  }
  return 'audio';
}

/**
 * Formats seconds into MM:SS.mmm (e.g., 00:14.280)
 */
export function formatMillisTimestamp(seconds: number): string {
  const safe = Math.max(0, seconds);
  const mins = Math.floor(safe / 60);
  const secs = Math.floor(safe % 60);
  const millis = Math.min(999, Math.round((safe - Math.floor(safe)) * 1000));
  return `${String(mins).padStart(2, '0')}:${String(secs).padStart(2, '0')}.${String(
    millis
  ).padStart(3, '0')}`;
}

/**
 * Formats seconds into MM:SS.cc for standard .LRC (e.g., 00:14.20)
 */
export function formatLrcTimestamp(seconds: number): string {
  const safe = Math.max(0, seconds);
  const mins = Math.floor(safe / 60);
  const secs = Math.floor(safe % 60);
  const hundredths = Math.min(99, Math.round((safe - Math.floor(safe)) * 100));
  return `${String(mins).padStart(2, '0')}:${String(secs).padStart(2, '0')}.${String(
    hundredths
  ).padStart(2, '0')}`;
}

/**
 * Formats seconds into HH:MM:SS,mmm (for SRT) or HH:MM:SS.mmm (for VTT)
 */
export function formatFullSubtitleTimestamp(
  seconds: number,
  separator: ',' | '.' = ','
): string {
  const safe = Math.max(0, seconds);
  const hrs = Math.floor(safe / 3600);
  const mins = Math.floor((safe % 3600) / 60);
  const secs = Math.floor(safe % 60);
  const millis = Math.min(999, Math.round((safe - Math.floor(safe)) * 1000));
  return `${String(hrs).padStart(2, '0')}:${String(mins).padStart(2, '0')}:${String(
    secs
  ).padStart(2, '0')}${separator}${String(millis).padStart(3, '0')}`;
}

/**
 * Formats seconds into MM:SS (e.g., 04:12)
 */
export function formatDurationShort(seconds: number): string {
  const safe = Math.max(0, Math.round(seconds));
  const mins = Math.floor(safe / 60);
  const secs = safe % 60;
  return `${String(mins).padStart(2, '0')}:${String(secs).padStart(2, '0')}`;
}

/**
 * Formats signed offset in seconds (e.g., "+0.450s", "0.000s", "-0.200s")
 */
export function formatSignedOffset(offsetSec: number): string {
  const fixed = Math.abs(offsetSec).toFixed(3);
  if (Math.abs(offsetSec) < 0.0005) return '0.000s';
  return `${offsetSec > 0 ? '+' : '-'}${fixed}s`;
}
